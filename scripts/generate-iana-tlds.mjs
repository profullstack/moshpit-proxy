#!/usr/bin/env node
// Regenerate the list of real top-level domains this proxy refuses to certify.
//
//   node scripts/generate-iana-tlds.mjs
//
// The local root is constrained by *exclusion* rather than by a permitted list.
// Permitting every Moshpit ending does not scale: there are 18224 of them, and
// naming each one puts a ~214 KB name-constraints extension into a certificate
// that is sent on every handshake. Excluding the 1438 real TLDs instead costs
// ~15 KB, needs no configuration, and covers every ending the registry sells —
// including ones sold after the root was minted.
//
// The property that matters survives the inversion. A root that permits
// `.hacker` and `.2600` cannot vouch for `google.com`; neither can a root that
// excludes every delegated TLD. What changes is that the second one does not
// have to be told what Moshpit sells.
//
// Vendored rather than fetched at run time: a proxy that phoned IANA on startup
// would mint an unconstrained root the moment IANA had a bad minute.
import { writeFile } from "node:fs/promises";

const SOURCE = "https://data.iana.org/TLD/tlds-alpha-by-domain.txt";
const TARGET = "lib/iana-tlds.ts";

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`IANA returned ${res.status}`);
const text = await res.text();

const version = text.split("\n")[0].replace(/^#\s*/, "").trim();
const tlds = text
  .split("\n")
  .map((line) => line.trim().toLowerCase())
  .filter((line) => line && !line.startsWith("#"))
  .sort();

if (tlds.length < 1000) throw new Error(`only ${tlds.length} TLDs parsed — refusing to write a short list`);

await writeFile(TARGET, `// Generated by scripts/generate-iana-tlds.mjs — do not edit by hand.
//
// Every top-level domain IANA delegates, as of:
//   ${version}
//
// The local root excludes these, which is what stops it vouching for the real
// internet. Everything else is a Moshpit ending, or is not resolvable here at
// all, so the proxy needs no list of what Moshpit currently sells.
export const IANA_VERSION = ${JSON.stringify(version)};

export const IANA_TLDS: ReadonlySet<string> = new Set([
${tlds.map((t) => `  ${JSON.stringify(t)},`).join("\n")}
]);

/** Is this ending a real top-level domain, rather than a Moshpit one? */
export function isRealTld(tld: string): boolean {
  return IANA_TLDS.has(String(tld ?? "").trim().toLowerCase());
}

/** The ending of a hostname, or "" when it has none. */
export function endingOf(name: string): string {
  const clean = String(name ?? "").trim().toLowerCase().replace(/\\.+$/, "");
  const at = clean.lastIndexOf(".");
  return at === -1 ? "" : clean.slice(at + 1);
}
`);

console.log(`wrote ${TARGET} (${tlds.length} TLDs, ${version})`);
